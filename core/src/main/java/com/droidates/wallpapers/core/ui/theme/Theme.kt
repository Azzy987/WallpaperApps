@Composable
fun WallpaperAppTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val view = LocalView.current

    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.DARK -> true
        ThemeMode.LIGHT -> false
    }

    // Material You dynamic colour is deliberately NOT used: it derives the palette
    // from the device wallpaper, which overrode each app's brand accent (a Pixel 11
    // build showed the phone's purple instead of its pink). Each app's accent comes
    // from its AppSpec — see brandPrimary in Color.kt.
    val colorScheme = if (darkTheme) darkScheme else lightScheme

    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            // Edge-to-edge itself is set once in MainActivity via enableEdgeToEdge().
            // setDecorFitsSystemWindows() is deprecated and Play Console flags it; calling
            // it here only repeated what enableEdgeToEdge already did.
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        content = content
    )
}
